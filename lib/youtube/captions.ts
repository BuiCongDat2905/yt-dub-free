import type { CaptionTrack, Cue } from "../subtitle/types.ts";
import { CaptionUnavailableError } from "../subtitle/types.ts";
import { parseJson3, parseVtt } from "../subtitle/parse.ts";

export function isAutoGenerated(track: CaptionTrack): boolean {
  return track.kind === "asr";
}

/**
 * Chọn track theo thứ tự: khớp ngôn ngữ ưu tiên và do người tạo -> khớp ngôn ngữ ưu tiên
 * (kể cả auto) -> track do người tạo bất kỳ -> track đầu tiên.
 */
export function pickTrack(tracks: CaptionTrack[], preferredLang = "en"): CaptionTrack | undefined {
  const valid = tracks.filter((track) => typeof track.baseUrl === "string" && track.baseUrl.length > 0);
  if (valid.length === 0) return undefined;

  const wanted = preferredLang.toLowerCase();
  const matchesLanguage = (track: CaptionTrack): boolean => {
    const code = (track.languageCode ?? "").toLowerCase();
    return code === wanted || code.startsWith(`${wanted}-`);
  };

  return (
    valid.find((track) => matchesLanguage(track) && !isAutoGenerated(track)) ??
    valid.find((track) => matchesLanguage(track)) ??
    valid.find((track) => !isAutoGenerated(track)) ??
    valid[0]
  );
}

export function withQuery(url: string, key: string, value: string): string {
  const parsed = new URL(url, "https://www.youtube.com");
  parsed.searchParams.set(key, value);
  return parsed.toString();
}

export async function fetchCuesForTrack(
  track: CaptionTrack,
  fetchImpl: typeof fetch = fetch,
  signal?: AbortSignal,
): Promise<Cue[]> {
  const response = await fetchImpl(withQuery(track.baseUrl, "fmt", "json3"), {
    credentials: "include",
    signal,
  });
  if (!response.ok) {
    throw new CaptionUnavailableError(`tải caption thất bại: HTTP ${response.status}`);
  }

  const raw = await response.text();
  if (raw.trim() === "") throw new CaptionUnavailableError("caption rỗng");

  const cues = raw.trimStart().startsWith("{") ? parseJson3(raw) : parseVtt(raw);
  if (cues.length === 0) throw new CaptionUnavailableError("không parse được cue nào từ caption");
  return cues;
}
